"""Export: write the world and its metadata into files other tools can open.

* ``points.ply``  binary PLY. Every vertex carries ``tag`` (index into the
                  annotation list, -1 = untagged); the annotation list itself,
                  units and up vector are embedded as JSON in header comments.
                  Opens in MeshLab, CloudCompare, Blender, Open3D, ...
* ``viewer.html`` a single self-contained page: orbit around the cloud, see
                  the tags, shift-click to add new ones, download them.
"""
from __future__ import annotations

import base64
import json
from importlib import resources
from pathlib import Path

import numpy as np

from .scene import Annotation, Scene

PLY_META_PREFIX = "scan3d "


def write_ply(scene: Scene, path: str | Path) -> None:
    labels = scene.point_labels()
    n = len(scene.points)
    meta = {
        "units": scene.units,
        "up": scene.up_vector().tolist(),
        "annotations": [a.to_dict() for a in scene.annotations],
    }
    header = [
        "ply",
        "format binary_little_endian 1.0",
        "comment generated by scan3d",
        # one comment line per key keeps lines short for picky readers
        *(f"comment {PLY_META_PREFIX}{k}={json.dumps(v, separators=(',', ':'))}" for k, v in meta.items()),
        f"element vertex {n}",
        "property float x",
        "property float y",
        "property float z",
        "property uchar red",
        "property uchar green",
        "property uchar blue",
        "property int tag",
        "end_header",
    ]
    dt = np.dtype([("x", "<f4"), ("y", "<f4"), ("z", "<f4"), ("r", "u1"), ("g", "u1"), ("b", "u1"), ("tag", "<i4")])
    arr = np.empty(n, dt)
    arr["x"], arr["y"], arr["z"] = scene.points.T
    arr["r"], arr["g"], arr["b"] = scene.colors.T
    arr["tag"] = labels
    with open(path, "wb") as f:
        f.write(("\n".join(header) + "\n").encode("ascii"))
        f.write(arr.tobytes())


def read_ply(path: str | Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, dict]:
    """Read a PLY written by ``write_ply``: (xyz, rgb, tag, metadata)."""
    data = Path(path).read_bytes()
    end = data.index(b"end_header\n") + len(b"end_header\n")
    meta, n = {}, 0
    for line in data[:end].decode("ascii").splitlines():
        if line.startswith(f"comment {PLY_META_PREFIX}"):
            k, v = line[len(f"comment {PLY_META_PREFIX}"):].split("=", 1)
            meta[k] = json.loads(v)
        elif line.startswith("element vertex"):
            n = int(line.split()[-1])
    dt = np.dtype([("x", "<f4"), ("y", "<f4"), ("z", "<f4"), ("r", "u1"), ("g", "u1"), ("b", "u1"), ("tag", "<i4")])
    arr = np.frombuffer(data[end:], dt, count=n)
    xyz = np.stack([arr["x"], arr["y"], arr["z"]], 1)
    rgb = np.stack([arr["r"], arr["g"], arr["b"]], 1)
    return xyz, rgb, arr["tag"].copy(), meta


def _b64(a: np.ndarray) -> str:
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode("ascii")


def viewer_payload(scene: Scene, max_points: int = 400_000) -> dict:
    pts, cols = scene.points, scene.colors
    if len(pts) > max_points:
        keep = np.random.default_rng(0).choice(len(pts), max_points, replace=False)
        pts, cols = pts[keep], cols[keep]
    centre = np.median(pts, axis=0) if len(pts) else np.zeros(3)
    return {
        "centre": centre.tolist(),
        "positions": _b64((pts - centre).astype(np.float32)),
        "colors": _b64(cols.astype(np.uint8)),
        "count": int(len(pts)),
        "up": scene.up_vector().tolist(),
        "units": scene.units,
        "info": scene.info,
        "cameras": [
            {"name": c.name, "center": (c.center - centre).tolist(), "R": c.R.tolist(), "K": c.K.tolist(),
             "width": c.width, "height": c.height}
            for c in scene.cameras
        ],
        "annotations": [dict(a.to_dict(), position=(np.asarray(a.position) - centre).tolist()) for a in scene.annotations],
    }


def write_viewer(scene: Scene, path: str | Path, title: str = "scan3d viewer") -> None:
    template = resources.files("scan3d").joinpath("viewer_template.html").read_text()
    payload = json.dumps(viewer_payload(scene), separators=(",", ":")).replace("</", "<\\/")
    html = template.replace("__TITLE__", title).replace("/*__SCENE_DATA__*/null", payload)
    Path(path).write_text(html)


def import_viewer_tags(scene: Scene, tags_json: str | Path) -> list[Annotation]:
    """Merge tags downloaded from the viewer (positions are already in world coordinates)."""
    data = json.loads(Path(tags_json).read_text())
    existing = {a.id for a in scene.annotations}
    added = []
    for d in data.get("annotations", data if isinstance(data, list) else []):
        a = Annotation.from_dict(d)
        if a.id in existing:
            scene.remove_annotation(a.id)
        scene.add_annotation(a)
        added.append(a)
    return added


def export_all(scene: Scene, out_dir: str | Path) -> None:
    from .floorplan import save_plan

    out = Path(out_dir)
    scene.save(out)
    write_ply(scene, out / "points.ply")
    write_viewer(scene, out / "viewer.html", title=f"scan3d - {out.resolve().name}")
    save_plan(scene, out)
